  /** Resolve a sprite to { rows, palette }, or null when the joker has no drawing yet. */
  function resolve(id) {
    const entry = SPRITES[id];
    if (!entry) return null;
    const base = entry.like ? SPRITES[entry.like] : entry;
    let rows = base.g;
    if (base.m) rows = rows.map((half) => half + [...half].reverse().slice(base.m === 2 ? 1 : 0).join(''));
    const width = Math.max(...rows.map((r) => r.length));
    rows = rows.map((r) => r.padEnd(width, '.'));
    // Trim transparent margins so every sprite centers on its visible pixels.
    while (rows.length && /^\.*$/.test(rows[0])) rows = rows.slice(1);
    while (rows.length && /^\.*$/.test(rows[rows.length - 1])) rows = rows.slice(0, -1);
    const used = (x) => rows.some((r) => r[x] !== '.');
    let left = 0;
    let right = width - 1;
    while (left < right && !used(left)) left++;
    while (right > left && !used(right)) right--;
    rows = rows.map((r) => r.slice(left, right + 1));
    return { rows, palette: { ...PALETTE, ...(base.p || {}), ...(entry.like ? entry.p : {}) } };
  }

  return { PALETTE, SPRITES, resolve };
