// Concatenate src/*.js into the browser module client.js: node scripts/build.cjs
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const read = (name) => fs.readFileSync(path.join(root, 'src', name), 'utf8')
  .split('\n')
  .filter((line) => !line.includes('// @node-only'))
  .join('\n');
const indent = (text) => text.split('\n').map((line) => (line ? `    ${line}` : line)).join('\n');

const font = fs.readFileSync(path.join(root, 'fonts', 'jkp-pixel.woff2')).toString('base64');
const rules = require('./rules-source.cjs');
const ui = ['base.js', 'hud.js', 'screens.js', 'overlays.js', 'page.js'].map((file) => read(`ui/${file}`)).join('\n');
const body = [rules(), ...['locale.js', 'locale-content.js', 'locale-jokers.js', 'art-jokers.js', 'art.js', 'fx.js', 'style.js'].map(read), `const JokerPokerUI = (() => {\n${ui}\n})();`, read('entry.js')]
  .join('\n')
  .replace('__FONT_DATA__', font);
const out = `// Generated by scripts/build.cjs from src/; edit the sources instead.
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory(require) {
    const React = require('react');
${indent(body)}
  },
});
`;
fs.writeFileSync(path.join(root, 'client.js'), out);
console.log(`wrote client.js (${out.length} bytes)`);
